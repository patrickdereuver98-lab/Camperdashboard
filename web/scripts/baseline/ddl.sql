-- Introspectie van het live schema (review november 2026, R5): levert per object een DDL-regel, in een volgorde die
-- op een schone Supabase-database zonder fouten draait. Eén rij per statement: (stap, sleutel, ddl).
-- Gebruikt door web/scripts/baseline/maak-baseline.py; alleen lezen, raakt geen data.
-- Bereik: schema's public en private, plus wat de app op andere schema's zet (triggers op auth.users, policies op
-- storage.objects, buckets, de realtime-publicatie). Zonder rijen, eigenaren en geheimen.
set search_path = '';

with
app_ns as (select oid, nspname from pg_namespace where nspname in ('public', 'private')),
ext_obj as (select objid from pg_depend where deptype = 'e'),
tabellen as (
  select c.oid, c.oid::regclass::text as naam, c.relrowsecurity, c.relacl, c.relowner
  from pg_class c join app_ns n on n.oid = c.relnamespace
  where c.relkind in ('r', 'p') and c.oid not in (select objid from ext_obj)
),
functies as (
  select p.oid, p.oid::regprocedure::text as sig, p.proacl, p.proowner
  from pg_proc p join app_ns n on n.oid = p.pronamespace
  where p.oid not in (select objid from ext_obj)
),
reeksen as (
  select c.oid, c.oid::regclass::text as naam, c.relacl, c.relowner, s.*
  from pg_class c join app_ns n on n.oid = c.relnamespace join pg_sequence s on s.seqrelid = c.oid
  where c.relkind = 'S' and c.oid not in (select objid from ext_obj)
    -- reeksen van identity-kolommen komen met de kolom mee
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
rol as (select oid, case when oid = 0 then 'public' else quote_ident(rolname) end as naam from pg_roles
        union all select 0, 'public'),
beheerrollen as (select 'public, anon, authenticated, service_role'::text as lijst)

-- 20: schema's
select 20 as stap, nspname::text as sleutel, format('create schema if not exists %I;', nspname) as ddl
from app_ns where nspname <> 'public'

-- 30: losse reeksen (serial-kolommen)
union all
select 30, naam, format('create sequence if not exists %s as %s increment by %s minvalue %s maxvalue %s start with %s cache %s%s;',
  naam, format_type(seqtypid, null), seqincrement, seqmin, seqmax, seqstart, seqcache, case when seqcycle then ' cycle' else '' end)
from reeksen

-- 40: tabellen met kolommen; standaardwaarden en constraints komen pas na de functies (stap 70 en 80)
union all
select 40, t.naam, format(E'create table if not exists %s (\n%s\n);', t.naam, coalesce((
  select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
    case when a.attcollation <> 0 and a.attcollation <> (select oid from pg_collation where collname = 'default')
              and a.attcollation <> (select typcollation from pg_type where oid = a.atttypid)
         then ' collate ' || (select quote_ident(collname) from pg_collation where oid = a.attcollation) else '' end,
    case a.attgenerated when 's' then format(' generated always as (%s) stored', pg_get_expr(d.adbin, d.adrelid)) else '' end
      || case a.attidentity when 'a' then ' generated always as identity' when 'd' then ' generated by default as identity' else '' end,
    case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
  from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped), ''))
from tabellen t

-- 50: eigenaar van losse reeksen
union all
select 50, r.naam, format('alter sequence %s owned by %s.%I;', r.naam, d.refobjid::regclass::text, a.attname)
from reeksen r join pg_depend d on d.objid = r.oid and d.deptype = 'a' and d.refobjsubid > 0
join pg_attribute a on a.attrelid = d.refobjid and a.attnum = d.refobjsubid

-- 60: functies (lichamen worden niet gecontroleerd: check_function_bodies staat uit)
union all
select 60, f.sig, pg_get_functiondef(f.oid) || ';' from functies f

-- 70: standaardwaarden (geen gegenereerde kolommen)
union all
select 70, t.naam || '.' || a.attname, format('alter table only %s alter column %I set default %s;', t.naam, a.attname, pg_get_expr(d.adbin, d.adrelid))
from tabellen t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped and a.attgenerated = ''
join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum

-- 80: constraints: eerst primaire en unieke sleutels, dan checks, dan verwijzingen
union all
select case co.contype when 'p' then 80 when 'u' then 81 when 'x' then 81 when 'c' then 82 else 83 end,
  t.naam || '.' || co.conname, format('alter table only %s add constraint %I %s;', t.naam, co.conname, pg_get_constraintdef(co.oid))
from tabellen t join pg_constraint co on co.conrelid = t.oid
where co.contype in ('p', 'u', 'c', 'f', 'x')

-- 90: indexen die niet bij een constraint horen
union all
select 90, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
from tabellen t join pg_index i on i.indrelid = t.oid
where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid and co.contype in ('p', 'u', 'x'))

-- 100: triggers op app-tabellen en triggers elders (auth.users) die een app-functie aanroepen
union all
select 100, tg.tgrelid::regclass::text || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
from pg_trigger tg join pg_class c on c.oid = tg.tgrelid
where not tg.tgisinternal
  and (c.relnamespace in (select oid from app_ns) or tg.tgfoid in (select oid from functies))

-- 110: rijbeveiliging
union all
select 110, t.naam, format('alter table %s enable row level security;', t.naam) from tabellen t where t.relrowsecurity

-- 120: policies op app-tabellen en op storage.objects
union all
select 120, pol.polrelid::regclass::text || '.' || pol.polname,
  format('create policy %I on %s as %s for %s to %s%s%s;', pol.polname, pol.polrelid::regclass::text,
    case when pol.polpermissive then 'permissive' else 'restrictive' end,
    case pol.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end,
    (select string_agg(case when r = 0 then 'public' else quote_ident(pg_get_userbyid(r)) end, ', ' order by 1) from unnest(pol.polroles) r),
    case when pol.polqual is not null then format(' using (%s)', pg_get_expr(pol.polqual, pol.polrelid)) else '' end,
    case when pol.polwithcheck is not null then format(' with check (%s)', pg_get_expr(pol.polwithcheck, pol.polrelid)) else '' end)
from pg_policy pol join pg_class c on c.oid = pol.polrelid
where c.relnamespace in (select oid from app_ns) or pol.polrelid = 'storage.objects'::regclass

-- 130: rechten op tabellen: eerst alles intrekken (een nieuw project geeft via default privileges te veel), dan
-- precies wat live staat. Een lege ACL betekent: alleen de eigenaar.
union all
select 130, t.naam, format('revoke all on table %s from %s;', t.naam, (select lijst from beheerrollen)) from tabellen t
union all
select 131, t.naam || ' ' || r.naam, format('grant %s on table %s to %s;', string_agg(lower(x.privilege_type), ', ' order by x.privilege_type), t.naam, r.naam)
from tabellen t cross join lateral aclexplode(coalesce(t.relacl, acldefault('r', t.relowner))) x
join rol r on r.oid = x.grantee
where x.grantee <> t.relowner
group by t.naam, r.naam

-- 132: kolomrechten
union all
select 132, t.naam || '.' || a.attname || ' ' || r.naam, format('grant %s (%I) on table %s to %s;', string_agg(lower(x.privilege_type), ', ' order by x.privilege_type), a.attname, t.naam, r.naam)
from tabellen t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped and a.attacl is not null
cross join lateral aclexplode(a.attacl) x join rol r on r.oid = x.grantee
where x.grantee <> t.relowner
group by t.naam, a.attname, r.naam

-- 133: rechten op reeksen
union all
select 133, s.naam, format('revoke all on sequence %s from %s;', s.naam, (select lijst from beheerrollen))
from (select oid, oid::regclass::text naam, relacl, relowner from pg_class where relkind = 'S' and relnamespace in (select oid from app_ns)) s
union all
select 134, s.naam || ' ' || r.naam, format('grant %s on sequence %s to %s;', string_agg(lower(x.privilege_type), ', ' order by x.privilege_type), s.naam, r.naam)
from (select oid, oid::regclass::text naam, relacl, relowner from pg_class where relkind = 'S' and relnamespace in (select oid from app_ns)) s
cross join lateral aclexplode(coalesce(s.relacl, acldefault('s', s.relowner))) x join rol r on r.oid = x.grantee
where x.grantee <> s.relowner
group by s.naam, r.naam

-- 135: rechten op functies (een lege ACL betekent: iedereen mag uitvoeren)
union all
select 135, f.sig, format('revoke all on function %s from %s;', f.sig, (select lijst from beheerrollen)) from functies f
union all
select 136, f.sig || ' ' || r.naam, format('grant execute on function %s to %s;', f.sig, r.naam)
from functies f cross join lateral aclexplode(coalesce(f.proacl, acldefault('f', f.proowner))) x join rol r on r.oid = x.grantee
where x.grantee <> f.proowner

-- 137: rechten op het schema private (public komt met het project mee)
union all
select 137, n.nspname || ' ' || r.naam, format('grant %s on schema %I to %s;', string_agg(lower(x.privilege_type), ', ' order by x.privilege_type), n.nspname, r.naam)
from pg_namespace n cross join lateral aclexplode(n.nspacl) x join rol r on r.oid = x.grantee
where n.nspname = 'private' and x.grantee <> n.nspowner
group by n.nspname, r.naam

-- 140: standaardrechten van postgres in de app-schema's (bepalen de rechten van nieuwe tabellen en functies)
union all
select 140, da.defaclobjtype::text || ' ' || coalesce(n.nspname, '-'),
  format('alter default privileges for role %I%s revoke all on %s from %s;', pg_get_userbyid(da.defaclrole),
    case when n.nspname is not null then ' in schema ' || quote_ident(n.nspname) else '' end,
    case da.defaclobjtype when 'r' then 'tables' when 'S' then 'sequences' when 'f' then 'functions' when 'T' then 'types' else 'schemas' end,
    'anon, authenticated, service_role')
from pg_default_acl da left join pg_namespace n on n.oid = da.defaclnamespace
where pg_get_userbyid(da.defaclrole) = 'postgres' and (n.nspname in ('public', 'private'))
union all
select 141, da.defaclobjtype::text || ' ' || n.nspname || ' ' || r.naam,
  format('alter default privileges for role %I in schema %I grant %s on %s to %s;', pg_get_userbyid(da.defaclrole), n.nspname,
    string_agg(lower(x.privilege_type), ', ' order by x.privilege_type),
    case da.defaclobjtype when 'r' then 'tables' when 'S' then 'sequences' when 'f' then 'functions' when 'T' then 'types' else 'schemas' end, r.naam)
from pg_default_acl da join pg_namespace n on n.oid = da.defaclnamespace
cross join lateral aclexplode(da.defaclacl) x join rol r on r.oid = x.grantee
where pg_get_userbyid(da.defaclrole) = 'postgres' and n.nspname in ('public', 'private') and x.grantee <> da.defaclrole
group by da.defaclrole, n.nspname, da.defaclobjtype, r.naam

-- 150: realtime-publicatie
union all
select 150, format('%I.%I', schemaname, tablename),
  format(E'do $$ begin\n  if exists (select 1 from pg_publication where pubname = %L) then\n    alter publication %I add table %I.%I;\n  end if;\nend $$;', pubname, pubname, schemaname, tablename)
from pg_publication_tables where schemaname in ('public', 'private')

-- 160: opslagbuckets (instellingen, geen bestanden)
union all
select 160, b.id, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %s) on conflict (id) do nothing;',
  b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'null'), coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
from storage.buckets b

order by 1, 2;
